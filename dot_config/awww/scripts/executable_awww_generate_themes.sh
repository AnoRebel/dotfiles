#!/bin/bash
# ── awww_generate_themes.sh ──────────────────────────────────────────
# Reads pywal colors from ~/.cache/wal/colors.sh and generates
# dynamic theme files for zellij, yazi, and superfile.
#
# Called from awww_randomize_multi.sh after each wallpaper change.
# Can also be run standalone to regenerate themes from current colors.

WAL_COLORS="$HOME/.cache/wal/colors.sh"

if [ ! -f "$WAL_COLORS" ]; then
	echo "awww_generate_themes: $WAL_COLORS not found, skipping" >&2
	exit 1
fi

# shellcheck source=/dev/null
source "$WAL_COLORS"

# ── Hex→RGB helper ──────────────────────────────────────────────────
# Zellij themes use space-separated RGB decimal values (e.g. "255 128 0")
hex_to_rgb() {
	local hex="${1#\#}"
	printf "%d %d %d" "0x${hex:0:2}" "0x${hex:2:2}" "0x${hex:4:2}"
}

# ── Color assignments (semantic mapping from pywal) ──────────────────
# background = color0   (darkest)
# foreground = color7   (lightest)
# color1 = red/accent1  (used for errors, highlights)
# color2 = green/accent2
# color3 = yellow/accent3
# color4 = blue/accent4
# color5 = magenta/accent5
# color6 = cyan/accent6
# color8 = bright black (dim text)

BG_RGB=$(hex_to_rgb "$background")
FG_RGB=$(hex_to_rgb "$foreground")
C0_RGB=$(hex_to_rgb "$color0")
C1_RGB=$(hex_to_rgb "$color1")
C2_RGB=$(hex_to_rgb "$color2")
C3_RGB=$(hex_to_rgb "$color3")
C4_RGB=$(hex_to_rgb "$color4")
C5_RGB=$(hex_to_rgb "$color5")
C6_RGB=$(hex_to_rgb "$color6")
C7_RGB=$(hex_to_rgb "$color7")
C8_RGB=$(hex_to_rgb "$color8")

# ═══════════════════════════════════════════════════════════════════════
# 1. ZELLIJ THEME
# ═══════════════════════════════════════════════════════════════════════
ZELLIJ_THEME="$HOME/.config/zellij/themes/pywal.kdl"

cat >"$ZELLIJ_THEME" <<EOF
// Auto-generated by awww_generate_themes.sh from pywal colors
// Source wallpaper: ${wallpaper:-unknown}
themes {
    pywal {
        // ── Text (bare UI text like Ctrl/Alt indicators) ────────
        text_unselected {
            base $FG_RGB
            background $BG_RGB
            emphasis_0 $C4_RGB
            emphasis_1 $C5_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }
        text_selected {
            base $BG_RGB
            background $C4_RGB
            emphasis_0 $FG_RGB
            emphasis_1 $C5_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }

        // ── Ribbons (tabs, mode indicators in status bar) ───────
        ribbon_unselected {
            base $FG_RGB
            background $C8_RGB
            emphasis_0 $C4_RGB
            emphasis_1 $C5_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }
        ribbon_selected {
            base $BG_RGB
            background $C4_RGB
            emphasis_0 $FG_RGB
            emphasis_1 $C5_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }

        // ── Tables (session manager, plugin manager) ────────────
        table_title {
            base $C5_RGB
            background $BG_RGB
            emphasis_0 $C4_RGB
            emphasis_1 $FG_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }
        table_cell_unselected {
            base $FG_RGB
            background $BG_RGB
            emphasis_0 $C4_RGB
            emphasis_1 $C5_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }
        table_cell_selected {
            base $BG_RGB
            background $C4_RGB
            emphasis_0 $FG_RGB
            emphasis_1 $C5_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }

        // ── Lists (nested lists in UI) ──────────────────────────
        list_unselected {
            base $FG_RGB
            background $BG_RGB
            emphasis_0 $C4_RGB
            emphasis_1 $C5_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }
        list_selected {
            base $BG_RGB
            background $C4_RGB
            emphasis_0 $FG_RGB
            emphasis_1 $C5_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }

        // ── Frames (pane borders) ───────────────────────────────
        frame_unselected {
            base $C8_RGB
            background $BG_RGB
            emphasis_0 $C4_RGB
            emphasis_1 $C5_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }
        frame_selected {
            base $C4_RGB
            background $BG_RGB
            emphasis_0 $C5_RGB
            emphasis_1 $FG_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }
        frame_highlight {
            base $C5_RGB
            background $BG_RGB
            emphasis_0 $C4_RGB
            emphasis_1 $FG_RGB
            emphasis_2 $C6_RGB
            emphasis_3 $C3_RGB
        }

        // ── Exit codes ──────────────────────────────────────────
        exit_code_success {
            base $C2_RGB
            background $BG_RGB
            emphasis_0 $C2_RGB
            emphasis_1 $C2_RGB
            emphasis_2 $C2_RGB
            emphasis_3 $C2_RGB
        }
        exit_code_error {
            base $C1_RGB
            background $BG_RGB
            emphasis_0 $C1_RGB
            emphasis_1 $C1_RGB
            emphasis_2 $C1_RGB
            emphasis_3 $C1_RGB
        }

        // ── Multiplayer ─────────────────────────────────────────
        multiplayer_user_colors {
            player_1 $C1_RGB
            player_2 $C2_RGB
            player_3 $C3_RGB
            player_4 $C4_RGB
            player_5 $C5_RGB
            player_6 $C6_RGB
            player_7 $C8_RGB
            player_8 $FG_RGB
            player_9 $C0_RGB
            player_10 $C7_RGB
        }
    }
}
EOF

echo "awww_generate_themes: wrote $ZELLIJ_THEME"

# ═══════════════════════════════════════════════════════════════════════
# 2. YAZI THEME
# ═══════════════════════════════════════════════════════════════════════
YAZI_THEME="$HOME/.config/yazi/theme.toml"

cat >"$YAZI_THEME" <<EOF
