    { mime = "image/*",               fg = "${color3}" },
    # Audio / Video
    { mime = "{audio,video}/*",       fg = "${color5}" },
    # Archives
    { mime = "application/{*zip,tar,bzip*,7z*,rar,xz}", fg = "${color1}" },
    # Documents
